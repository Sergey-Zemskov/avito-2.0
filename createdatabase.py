import os
import fdb


DB_PATH = "/opt/avito_db/AVITO.DB"
HOST = "localhost"
USER = "sysdba"
PASSWORD = "masterkey"
CHARSET = "UTF8"


def table_exists(cursor, table_name):
    """Проверка существования таблицы."""

    cursor.execute(
        """
        SELECT 1
        FROM RDB$RELATIONS
        WHERE RDB$RELATION_NAME = ?
        AND COALESCE(RDB$SYSTEM_FLAG, 0) = 0
        """,
        (table_name.upper(),)
    )

    return cursor.fetchone() is not None


def create_database():
    """Создание базы или подключение к существующей."""

    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)

    try:
        # Сначала пробуем подключиться к существующей базе
        print("Проверка существующей базы данных...")

        connection = fdb.connect(
            dsn=f"{HOST}:{DB_PATH}",
            user=USER,
            password=PASSWORD,
            charset=CHARSET
        )

        print("Подключение к существующей базе выполнено.")

    except fdb.DatabaseError:
        # Если подключиться не удалось, пробуем создать базу
        print("Существующая база недоступна. Попытка создания...")

        try:
            connection = fdb.create_database(
                database=f"{HOST}:{DB_PATH}",
                user=USER,
                password=PASSWORD,
                charset=CHARSET
            )

            print("База данных создана.")

        except fdb.DatabaseError as error:
            print("Не удалось создать или открыть базу данных:")
            print(error)
            return

    cursor = connection.cursor()

    try:
        # Таблица пользователей
        if not table_exists(cursor, "USERS"):
            cursor.execute("""
                CREATE TABLE users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    login VARCHAR(50) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    role VARCHAR(20) DEFAULT 'user'
                )
            """)
            print("Создана таблица users.")

        # Таблица категорий
        if not table_exists(cursor, "CATEGORIES"):
            cursor.execute("""
                CREATE TABLE categories (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    description VARCHAR(500)
                )
            """)
            print("Создана таблица categories.")

        # Таблица объявлений
        if not table_exists(cursor, "ADS"):
            cursor.execute("""
                CREATE TABLE ads (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    category_id INTEGER NOT NULL,
                    title VARCHAR(200) NOT NULL,
                    description VARCHAR(2000),
                    price NUMERIC(12, 2) NOT NULL,
                    city VARCHAR(100),
                    image_url VARCHAR(500),

                    FOREIGN KEY (user_id)
                        REFERENCES users(id)
                        ON DELETE CASCADE,

                    FOREIGN KEY (category_id)
                        REFERENCES categories(id)
                )
            """)
            print("Создана таблица ads.")

        # Таблица избранного
        if not table_exists(cursor, "FAVORITES"):
            cursor.execute("""
                CREATE TABLE favorites (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    ad_id INTEGER NOT NULL,

                    UNIQUE (user_id, ad_id),

                    FOREIGN KEY (user_id)
                        REFERENCES users(id)
                        ON DELETE CASCADE,

                    FOREIGN KEY (ad_id)
                        REFERENCES ads(id)
                        ON DELETE CASCADE
                )
            """)
            print("Создана таблица favorites.")

        # Таблица сообщений
        if not table_exists(cursor, "MESSAGES"):
            cursor.execute("""
                CREATE TABLE messages (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sender_id INTEGER NOT NULL,
                    receiver_id INTEGER NOT NULL,
                    ad_id INTEGER,
                    message_text VARCHAR(2000) NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                    FOREIGN KEY (sender_id)
                        REFERENCES users(id)
                        ON DELETE CASCADE,

                    FOREIGN KEY (receiver_id)
                        REFERENCES users(id)
                        ON DELETE CASCADE,

                    FOREIGN KEY (ad_id)
                        REFERENCES ads(id)
                        ON DELETE SET NULL
                )
            """)
            print("Создана таблица messages.")

        # Добавление категорий, если таблица пустая
        cursor.execute("SELECT COUNT(*) FROM categories")
        count = cursor.fetchone()[0]

        if count == 0:
            categories = [
                ("Электроника", "Телефоны и техника"),
                ("Одежда", "Одежда и обувь"),
                ("Дом и сад", "Товары для дома"),
                ("Транспорт", "Автомобили и транспорт"),
                ("Недвижимость", "Квартиры и дома"),
                ("Хобби", "Спорт и увлечения"),
                ("Другое", "Прочие товары")
            ]

            for category in categories:
                cursor.execute(
                    """
                    INSERT INTO categories (name, description)
                    VALUES (?, ?)
                    """,
                    category
                )

            print("Добавлены категории.")

        connection.commit()

        print("Проверка и создание таблиц завершены.")

    except Exception as error:
        connection.rollback()
        print("Ошибка при работе с таблицами:")
        print(error)

    finally:
        cursor.close()
        connection.close()


if __name__ == "__main__":
    create_database()
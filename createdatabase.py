import fdb
import os

# На Linux сохраняем в домашнюю папку пользователя
DB_DIR = os.path.expanduser("~/avito_db")
DB_PATH = os.path.join(DB_DIR, "AVITO.DB")

HOST = "localhost"
USER = "sysdba"
PASSWORD = "masterkey"

def create_database():
    if not os.path.exists(DB_DIR):
        os.makedirs(DB_DIR)
    
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)
        print("Старая база удалена.")

    conn = fdb.create_database(
        dsn=f"{HOST}:{DB_PATH}",
        user=USER, password=PASSWORD, charset="UTF8"
    )
    cur = conn.cursor()

    # 1. Пользователи
    cur.execute("""CREATE TABLE users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        login VARCHAR(50) UNIQUE NOT NULL,
        password_hash VARCHAR(255) NOT NULL,
        role VARCHAR(20) NOT NULL
    )""")

    # 2. Категории
    cur.execute("""CREATE TABLE categories (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) UNIQUE NOT NULL
    )""")

    # 3. Объявления (фото в BLOB)
    cur.execute("""CREATE TABLE ads (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        category_id INTEGER NOT NULL,
        title VARCHAR(255) NOT NULL,
        description VARCHAR(2000),
        price NUMERIC(12, 2) NOT NULL,
        city VARCHAR(100) NOT NULL,
        image BLOB,
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
    )""")

    # 4. Избранное
    cur.execute("""CREATE TABLE favorites (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        ad_id INTEGER NOT NULL,
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (ad_id) REFERENCES ads(id) ON DELETE CASCADE,
        UNIQUE (user_id, ad_id)
    )""")

    # 5. Сообщения
    cur.execute("""CREATE TABLE messages (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sender_id INTEGER NOT NULL,
        receiver_id INTEGER NOT NULL,
        ad_id INTEGER,
        message_text VARCHAR(2000) NOT NULL,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (receiver_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (ad_id) REFERENCES ads(id) ON DELETE CASCADE
    )""")

    # Добавляем базовые категории
    for cat in ['Электроника', 'Транспорт', 'Недвижимость', 'Услуги']:
        cur.execute("INSERT INTO categories (name) VALUES (?)", (cat,))

    conn.commit()
    cur.close()
    conn.close()
    print(f"База успешно создана: {DB_PATH}")

if __name__ == "__main__":
    create_database()
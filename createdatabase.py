# Создание базы данных Avito с тестовыми данными.
# ВНИМАНИЕ: при запуске существующая база удаляется!

import os
import random
import hashlib
import fdb
from faker import Faker

DB_DIR = '/opt/avito_db'
DB_PATH = os.path.join(DB_DIR, 'AVITO.DB')
DB_DSN = 'localhost:' + DB_PATH
USER = 'sysdba'
PASSWORD = 'masterkey'
CHARSET = 'UTF8'

fake = Faker('ru_RU')
random.seed(10)
Faker.seed(10)

CATEGORIES = [
    ('Электроника', 'Телефоны, компьютеры и техника'),
    ('Транспорт', 'Автомобили и запчасти'),
    ('Недвижимость', 'Квартиры, дома и помещения'),
    ('Услуги', 'Услуги специалистов'),
    ('Работа', 'Вакансии и резюме'),
    ('Личные вещи', 'Одежда, обувь и аксессуары'),
]


def remove_old_database():
    """Удаляет базу Firebird, если она существует."""
    if not os.path.exists(DB_PATH):
        print('Старой базы нет.')
        return

    print('Удаление старой базы...')
    conn = None
    try:
        conn = fdb.connect(dsn=DB_DSN, user=USER, password=PASSWORD, charset=CHARSET)
        conn.drop_database()
        conn = None
        print('Старая база удалена.')
    except Exception as error:
        if conn:
            try:
                conn.close()
            except Exception:
                pass
        raise RuntimeError(
            'Не получилось удалить старую базу. Останови app.py и проверь права '
            'пользователя firebird на папку /opt/avito_db. Причина: ' + str(error)
        )


def create_tables(cursor):
    cursor.execute('''CREATE TABLE users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        login VARCHAR(50) UNIQUE NOT NULL,
        password_hash VARCHAR(255) NOT NULL,
        role VARCHAR(20) NOT NULL)''')

    cursor.execute('''CREATE TABLE categories (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) UNIQUE NOT NULL,
        description VARCHAR(1000))''')

    cursor.execute('''CREATE TABLE ads (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        category_id INTEGER NOT NULL,
        title VARCHAR(255) NOT NULL,
        description VARCHAR(2000),
        price NUMERIC(12, 2) NOT NULL,
        city VARCHAR(100) NOT NULL,
        image BLOB SUB_TYPE BINARY,
        image_type VARCHAR(100),
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE)''')

    cursor.execute('''CREATE TABLE favorites (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL,
        ad_id INTEGER NOT NULL,
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (ad_id) REFERENCES ads(id) ON DELETE CASCADE,
        UNIQUE (user_id, ad_id))''')

    cursor.execute('''CREATE TABLE messages (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sender_id INTEGER NOT NULL,
        receiver_id INTEGER NOT NULL,
        ad_id INTEGER,
        message_text VARCHAR(2000) NOT NULL,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (receiver_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY (ad_id) REFERENCES ads(id) ON DELETE CASCADE)''')


def add_test_data(cursor):
    # Учётные записи для демонстрации. Пароль всех тестовых пользователей: 123456
    test_password = hashlib.sha256('123456'.encode('utf-8')).hexdigest()
    logins = ['student', 'ivan', 'anna', 'petr', 'olga', 'sergey', 'admin']
    for login in logins:
        role = 'admin' if login == 'admin' else 'user'
        cursor.execute('INSERT INTO users (login, password_hash, role) VALUES (?, ?, ?)',
                       (login, test_password, role))
    cursor.execute('SELECT id FROM users ORDER BY id')
    users = [r[0] for r in cursor.fetchall()]

    for name, description in CATEGORIES:
        cursor.execute('INSERT INTO categories (name, description) VALUES (?, ?)', (name, description))
    cursor.execute('SELECT id FROM categories ORDER BY id')
    categories = [r[0] for r in cursor.fetchall()]

    titles = [
        'Смартфон в хорошем состоянии', 'Ноутбук для учёбы', 'Велосипед городской',
        'Кресло компьютерное', 'Продам письменный стол', 'Наушники беспроводные',
        'Куртка зимняя', 'Монитор 24 дюйма', 'Кофемашина', 'Настольная лампа'
    ]
    for i in range(35):
        title = titles[i % len(titles)] + (f' ({i + 1})' if i >= len(titles) else '')
        cursor.execute('''INSERT INTO ads
            (user_id, category_id, title, description, price, city, image, image_type)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)''',
            (random.choice(users), random.choice(categories), title,
             fake.text(max_nb_chars=250), random.randint(500, 90000),
             random.choice(['Москва', 'Санкт-Петербург', 'Казань', 'Самара', 'Екатеринбург']),
             None, None))
    cursor.execute('SELECT id FROM ads ORDER BY id')
    ads = [r[0] for r in cursor.fetchall()]

    # Избранное
    fav_pairs = set()
    while len(fav_pairs) < 25:
        fav_pairs.add((random.choice(users), random.choice(ads)))
    for pair in fav_pairs:
        cursor.execute('INSERT INTO favorites (user_id, ad_id) VALUES (?, ?)', pair)

    # Несколько тестовых сообщений между student и другими аккаунтами
    student_id = users[0]
    for other_id in users[1:5]:
        ad_id = random.choice(ads)
        cursor.execute('''INSERT INTO messages (sender_id, receiver_id, ad_id, message_text)
            VALUES (?, ?, ?, ?)''', (student_id, other_id, ad_id, 'Здравствуйте! Объявление ещё актуально?'))
        cursor.execute('''INSERT INTO messages (sender_id, receiver_id, ad_id, message_text)
            VALUES (?, ?, ?, ?)''', (other_id, student_id, ad_id, 'Да, объявление актуально.'))


def create_database():
    os.makedirs(DB_DIR, exist_ok=True)
    connection = None
    cursor = None
    try:
        remove_old_database()
        print('Создание базы...')
        connection = fdb.create_database(database=DB_DSN, user=USER, password=PASSWORD, charset=CHARSET)
        cursor = connection.cursor()
        create_tables(cursor)
        add_test_data(cursor)
        connection.commit()
        print('База создана успешно:', DB_PATH)
        print('Тестовый вход: student / 123456')
        print('Объявления: 35, тестовых переписок: 4')
    except Exception as error:
        if connection:
            connection.rollback()
        print('Ошибка создания базы:', error)
        raise
    finally:
        if cursor:
            cursor.close()
        if connection:
            connection.close()


if __name__ == '__main__':
    create_database()

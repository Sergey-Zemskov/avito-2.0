import os
import fdb


# Настройки подключения
DB_PATH = "/opt/avito_db/AVITO.DB"
HOST = "localhost"
USER = "sysdba"
PASSWORD = "masterkey"
CHARSET = "UTF8"


def create_database():
    """Создание базы данных."""

    # Создаём папку для базы, если её ещё нет
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)

    # Не удаляем существующую базу
    if os.path.exists(DB_PATH):
        print("База данных уже существует.")
        return

    print("Создание базы данных...")

    connection = fdb.create_database(
        database=f"{HOST}:{DB_PATH}",
        user=USER,
        password=PASSWORD,
        charset=CHARSET
    )

    cursor = connection.cursor()

    try:
        # Таблица пользователей
        cursor.execute("""
            CREATE TABLE users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                login VARCHAR(50) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                role VARCHAR(20) DEFAULT 'user'
            )
        """)

        # Таблица категорий
        cursor.execute("""
            CREATE TABLE categories (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                description VARCHAR(500)
            )
        """)

        # Таблица объявлений
        cursor.execute("""
            CREATE TABLE ads (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                category_id INTEGER NOT NULL,
                title VARCHAR(200) NOT NULL,
                description VARCHAR(2000),
                price NUMERIC(12, 2) NOT NULL,
                city VARCHAR(100),
                image_url VARCHAR(500),

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (category_id)
                    REFERENCES categories(id)
            )
        """)

        # Таблица избранного
        cursor.execute("""
            CREATE TABLE favorites (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                ad_id INTEGER NOT NULL,

                UNIQUE (user_id, ad_id),

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (ad_id)
                    REFERENCES ads(id)
                    ON DELETE CASCADE
            )
        """)

        # Таблица сообщений
        cursor.execute("""
            CREATE TABLE messages (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sender_id INTEGER NOT NULL,
                receiver_id INTEGER NOT NULL,
                ad_id INTEGER,
                message_text VARCHAR(2000) NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (sender_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (receiver_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (ad_id)
                    REFERENCES ads(id)
                    ON DELETE SET NULL
            )
        """)

        # Добавляем основные категории
        categories = [
            ("Электроника", "Телефоны, компьютеры и техника"),
            ("Одежда", "Одежда, обувь и аксессуары"),
            ("Дом и сад", "Товары для дома и сада"),
            ("Транспорт", "Автомобили и другие виды транспорта"),
            ("Недвижимость", "Квартиры, дома и помещения"),
            ("Хобби", "Спорт, отдых и увлечения"),
            ("Другое", "Прочие товары")
        ]

        for category in categories:
            cursor.execute(
                """
                INSERT INTO categories (name, description)
                VALUES (?, ?)
                """,
                category
            )

        connection.commit()

        print("База данных успешно создана.")
        print("Таблицы и категории добавлены.")

    except Exception as error:
        connection.rollback()
        print("Ошибка создания базы данных:", error)

    finally:
        cursor.close()
        connection.close()


if __name__ == "__main__":
    create_database()
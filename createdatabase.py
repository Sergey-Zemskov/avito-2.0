import fdb
import os

# Путь, где будет создана база (в домашней папке пользователя)
DB_DIR = os.path.expanduser("~/avito_db")
DB_PATH = os.path.join(DB_DIR, "AVITO.DB")

HOST = "localhost"
USER = "sysdba"
PASSWORD = "masterkey"
CHARSET = "UTF8"

def create_database():
    # Создаем папку, если ее нет
    if not os.path.exists(DB_DIR):
        os.makedirs(DB_DIR)
    
    # Удаляем старую базу, если она есть (чтобы применить новую схему с BLOB)
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)
        print("Старая база удалена.")

    # Создаем новую базу
    conn = fdb.create_database(
        dsn=f"{HOST}:{DB_PATH}",
        user=USER,
        password=PASSWORD,
        charset=CHARSET
    )
    cur = conn.cursor()
    print("Файл базы данных успешно создан!")

    # 1. Пользователи
    cur.execute("""
        CREATE TABLE users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            login VARCHAR(50) UNIQUE NOT NULL,
            password_hash VARCHAR(255) NOT NULL,
            role VARCHAR(20) NOT NULL
        )
    """)

    # 2. Категории
    cur.execute("""
        CREATE TABLE categories (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name VARCHAR(100) UNIQUE NOT NULL,
            description VARCHAR(1000)
        )
    """)

    # 3. Объявления (фото теперь BLOB!)
    cur.execute("""
        CREATE TABLE ads (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            category_id INTEGER NOT NULL,
            title VARCHAR(255) NOT NULL,
            description VARCHAR(2000),
            price NUMERIC(12, 2) NOT NULL,
            city VARCHAR(100) NOT NULL,
            image BLOB,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
        )
    """)

    # 4. Избранное
    cur.execute("""
        CREATE TABLE favorites (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            ad_id INTEGER NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (ad_id) REFERENCES ads(id) ON DELETE CASCADE,
            UNIQUE (user_id, ad_id)
        )
    """)

    # 5. Сообщения
    cur.execute("""
        CREATE TABLE messages (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sender_id INTEGER NOT NULL,
            receiver_id INTEGER NOT NULL,
            ad_id INTEGER,
            message_text VARCHAR(2000) NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (receiver_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (ad_id) REFERENCES ads(id) ON DELETE CASCADE
        )
    """)

    # Добавим пару базовых категорий для старта
    cur.execute("INSERT INTO categories (name) VALUES ('Электроника')")
    cur.execute("INSERT INTO categories (name) VALUES ('Транспорт')")
    cur.execute("INSERT INTO categories (name) VALUES ('Недвижимость')")
    cur.execute("INSERT INTO categories (name) VALUES ('Услуги')")

    conn.commit()
    cur.close()
    conn.close()
    print(f"Все таблицы созданы. База сохранена: {DB_PATH}")

if __name__ == "__main__":
    create_database()